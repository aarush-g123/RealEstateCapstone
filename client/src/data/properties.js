export function formatPrice(n, status) {
  const formatted = n.toLocaleString("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0,
  });
  return status === "For Rent" ? `${formatted}/mo` : formatted;
}
